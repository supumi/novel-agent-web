// 写作风格锚点：给模型看「什么叫好」，而不是「别写什么」
//
// 核心判断：禁令清单（「不要写抽象比喻」）对小模型近乎无效，
// 因为它只说了不写什么，没说该写什么。模型会转向下一个同样空泛的套路。
// 正例示范的效果远好于禁令——它给出的是「质感的目标」，模型能照着调整。

/**
 * 示范片段：人写的网文 vs 模型典型写法
 * 用「对照 + 只讲差异」的方式给模型看，比抽象描述有效得多
 */
export const STYLE_EXAMPLES = `
【什么是好的网文（示范）】

沈砚把烟摁灭在鞋底，蹭了两下，把烟蒂摁进铁盒盖子。

“档案室晚上十一点锁门。”老陈说，“你别硬闯。”

沈砚没接话。他摸出那张卡，在灯下翻了个面。卡背面的字磨得快看不清了，只剩一个“八”。

“陈叔。”他终于开口，“七年前的编号，你还记得几个？”

老陈把铁盒盖上，咔的一声。

“一个都不记得。”

他往门口走，走到一半又停下，背对着他。

“那你别查了。查出来你也认不出。”

——注意这一段里没有一句解释情绪的话。“一个都不记得”之后没有
“他感到一阵失望”，也没有“他终于明白老陈已经不会帮他了”。
读者自己会得出结论。留白不等于总结。


【什么是典型的 AI 写法（反面示范，不要这样写】

“有些事你得自己去看。”苏晚说，“我告诉你答案，你不会信。信了，你也不会认。”

沈砚没有回答。有些话说出口就收不回来。

他终于明白，有些门推开了就再也关不上。

——问题在哪：
1. “有些事…”用抽象概括代替了具体内容
2. “你不会信。信了，你也不会认。”三个分句长度相同、结构对称，太工整
3. “他没有回答。有些话…”用否定句起头再总结，模仿留白的套路
4. “他终于明白，有些门…”格言式收尾，每段都想总结点什么
5. “声音比自己预想的要低”——用比较结构代替了声音本身

真人写手不会这么写，因为真人在现场只想着一件事：这句话怎么落到地上。


【写作的核心原则：写具体，不写感受】

这是唯一需要记住的一条。其余都是它的推论。

“具体”指：
  · 物件——铁盒、烟蒂、卡背面的字、鞋底的灰
  · 动作——蹭了两下、翻了个面、盖上、咔的一声
  · 生理反应——手指停在门把上，没按下去
  · 数字与事实——七年前、十一���、一个都不记得

“不写感受”指：
  × 不命名情绪（他很愤怒 / 她感到一阵）
  × 不作比喻（本体的对象是抽象情绪，而不是具体物件）
  × 不下判断（他终于明白 / 他意识到）
  × 不用连接词宣布转折（显然、其实、不知为何）

当你想写“他很难过”时，问自己：他手里正在做什么？
手在做什么就是答案。“他的手停在门把上，没按下去”胜过一切情绪描写。


【对话的写法】

对话里的人不是在传递信息，是在做别的事：试探、拖延、掩饰、回避。

所以：
  · 对话标签不要带补充说明。写“他说了句话”，不写“他说，声音比平时低”
  · 不要让对话工整对称。“你不会信。信了，你也不会认。”这种三段对仗太像写诗
  · 关键的话要说得笨。真人紧张时说不出漂亮句子
  · 沉默也是内容。“一个都不记得”之后不要再解释

好的对话读起来像偷听到的，不像写出来的。


【场景的写法】

场景不是氛围，是这个地点独有的东西。

坏：月光洒在窗台上，空气中弥漫着旧书的气息。
    （换个场景这句话照样能用，说明它不属于这个场景）

好：屋檐还在滴水。水滴砸在台阶上，节奏很稳。
    （这是这个场景独有的，无法搬到别处）

写场景时问自己：这个人站在这里，手能碰到什么？眼睛能看见什么？
然后只写那些。


【节奏的写法】

不要每段都完整。一段话说完一件事就够了。

真人写手的段落是碎的：一句对话，一段动作，一个细节，然后突然跳到别处。
AI 的段落是匀称的：每段长度相近，每段都有起承转合。

宁可写三行就停，不要为了段落完整而填话。
`;

