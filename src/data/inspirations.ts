/** 按题材筛选（'全部' 返回全量） */
export function filterInspirations(tag: InspirationTag | '全部'): Inspiration[] {
  return tag === '全部' ? INSPIRATIONS : INSPIRATIONS.filter((i) => i.tag === tag);
}

/** 无放回随机取 n 条，尽量避开 exclude 里的 id */
export function sampleInspirations(
  pool: Inspiration[],
  n: number,
  exclude: string[] = [],
): Inspiration[] {
  const fresh = pool.filter((i) => !exclude.includes(i.id));
  const src = fresh.length >= n ? fresh : pool;
  const out: Inspiration[] = [];
  const used = new Set<number>();
  while (out.length < n && used.size < src.length) {
    const idx = Math.floor(Math.random() * src.length);
    if (used.has(idx)) continue;
    used.add(idx);
    out.push(src[idx]);
  }
  return out;
}
